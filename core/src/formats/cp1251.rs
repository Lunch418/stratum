//! Перекодировка CP1251, в которой записаны все файлы Stratum 2000.
//!
//! Внешних крейтов ядро не тянет, поэтому таблица лежит здесь. Байты 0x00-0x7F
//! совпадают с ASCII, старшая половина — таблица ниже.

/// Верхняя половина CP1251: символы для байтов 0x80-0xFF.
const HIGH: [char; 128] = [
    'Ђ', 'Ѓ', '‚', 'ѓ', '„', '…', '†', '‡', '€', '‰', 'Љ', '‹', 'Њ', 'Ќ', 'Ћ', 'Џ',
    'ђ', '‘', '’', '“', '”', '•', '–', '—', '\u{98}', '™', 'љ', '›', 'њ', 'ќ', 'ћ', 'џ',
    '\u{a0}', 'Ў', 'ў', 'Ј', '¤', 'Ґ', '¦', '§', 'Ё', '©', 'Є', '«', '¬', '\u{ad}', '®', 'Ї',
    '°', '±', 'І', 'і', 'ґ', 'µ', '¶', '·', 'ё', '№', 'є', '»', 'ј', 'Ѕ', 'ѕ', 'ї',
    'А', 'Б', 'В', 'Г', 'Д', 'Е', 'Ж', 'З', 'И', 'Й', 'К', 'Л', 'М', 'Н', 'О', 'П',
    'Р', 'С', 'Т', 'У', 'Ф', 'Х', 'Ц', 'Ч', 'Ш', 'Щ', 'Ъ', 'Ы', 'Ь', 'Э', 'Ю', 'Я',
    'а', 'б', 'в', 'г', 'д', 'е', 'ж', 'з', 'и', 'й', 'к', 'л', 'м', 'н', 'о', 'п',
    'р', 'с', 'т', 'у', 'ф', 'х', 'ц', 'ч', 'ш', 'щ', 'ъ', 'ы', 'ь', 'э', 'ю', 'я',
];

/// Декодирует байты CP1251 в строку. Замен нет: таблица покрывает все 256 байт.
pub fn decode(bytes: &[u8]) -> String {
    let mut s = String::with_capacity(bytes.len());
    for &b in bytes {
        if b < 0x80 {
            s.push(b as char);
        } else {
            s.push(HIGH[(b - 0x80) as usize]);
        }
    }
    s
}

/// Кодирует строку обратно в CP1251. Символы вне таблицы заменяются на `?`,
/// поэтому для экспорта в старый формат текст нужно проверять заранее.
pub fn encode(text: &str) -> Vec<u8> {
    let mut out = Vec::with_capacity(text.len());
    for ch in text.chars() {
        if (ch as u32) < 0x80 {
            out.push(ch as u8);
        } else if let Some(i) = HIGH.iter().position(|&c| c == ch) {
            out.push(0x80 + i as u8);
        } else {
            out.push(b'?');
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn round_trip_russian() {
        let bytes = b"\xef\xeb\xe0\xed\xe5\xf2\xe0";
        assert_eq!(decode(bytes), "планета");
        assert_eq!(encode("планета"), bytes);
    }

    #[test]
    fn ascii_is_unchanged() {
        assert_eq!(decode(b"FLOAT x,y"), "FLOAT x,y");
    }
}
